import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import * as temporaryFile from "../lib/internal/temporaryFile";
import { runCheckSuppressions } from "./runCheckSuppressions";

const WORKSPACE_ROOT = path.resolve(__dirname, "../../../..");
// Oxlint loads JavaScript plugins as JavaScript, so these tests use the build that `test` depends on.
const PLUGIN = path.join(WORKSPACE_ROOT, "dist/packages/oxlint-plugin/src/index.js");

describe("runCheckSuppressions", () => {
  let repository: string;

  beforeEach(() => {
    repository = mkdtempSync(path.join(tmpdir(), "check-suppressions-"));
    symlinkSync(path.join(WORKSPACE_ROOT, "node_modules"), path.join(repository, "node_modules"));
    writeFiles({
      ".gitignore": "node_modules\n",
      "package.json": '{ "private": true }\n',
      "src/existing.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });
    git("init", "--quiet", "--initial-branch=main");
    git("add", "--all");
    git(
      "-c",
      "user.name=test",
      "-c",
      "user.email=test@example.com",
      "commit",
      "--quiet",
      "-m",
      "base",
    );
    git("branch", "base");
  });

  afterEach(() => {
    rmSync(repository, { force: true, recursive: true });
  });

  it("passes when no changed file adds a directive", () => {
    writeFiles({ "src/clean.ts": "export const value = 1;\n" });

    const { exitCode, output } = check();

    expect({ exitCode, output }).toStrictEqual({
      exitCode: 0,
      output: "cb-check-suppressions: checked 1 changed file(s); no violations.\n",
    });
  });

  it("checks added and changed directives and leaves untouched ones alone", () => {
    writeFiles({
      "src/existing.ts":
        "// oxlint-disable-next-line no-console\nconsole.log(1);\n// oxlint-disable-next-line no-console -- ditto\nconsole.log(2);\n",
      "src/added.ts":
        "// oxlint-disable-next-line typescript/no-explicit-any -- The SDK ships no types.\nexport const value: any = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain('src/existing.ts:3: Reason "ditto" is too generic.');
    expect(output).toContain(
      "src/added.ts:1: `typescript/no-explicit-any` must not be suppressed.",
    );
    expect(output).not.toContain("src/existing.ts:1:");
  });

  it("catches a file-level disable of the policy rule, which lint cannot see", () => {
    writeFiles({
      "src/generated.ts":
        "/* oxlint-disable @clipboard-health/suppression-policy -- Generated by the schema build. */\nexport const value = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain(
      "src/generated.ts:1: `@clipboard-health/suppression-policy` enforces the suppression policy",
    );
  });

  it("maps directives after non-ASCII text to their own lines", () => {
    writeFiles({
      "src/existing.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
      "src/unicode.ts":
        "export const label = 'Añadir turno — ✓';\n/* oxlint-disable-next-line no-console --\n   legacy */\nconsole.log(label);\n",
    });
    git("add", "--all");
    commit("unicode");
    writeFiles({
      "src/existing.ts":
        "// Añadir turno — ✓\n// oxlint-disable-next-line no-console\nconsole.log(2);\n",
      "src/unicode.ts":
        "export const label = 'Añadir turno — ✓';\n/* oxlint-disable-next-line no-console --\n   ok */\nconsole.log(label);\n",
    });

    const { exitCode, output } = check({ args: ["--base", "HEAD"] });

    expect(exitCode).toBe(1);
    expect(output).toContain('src/unicode.ts:2: Reason "ok" is too generic.');
    expect(output).not.toContain("src/existing.ts");
  });

  it("fails when Oxlint cannot parse a changed file instead of reporting no violations", () => {
    writeFiles({
      "src/broken.ts": "// oxlint-disable-next-line no-console\nconst value = ;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/broken.ts: Unexpected token");
    expect(output).not.toContain("no violations");
  });

  it("reports a blanket disable with a reason that directly follows the keyword", () => {
    writeFiles({
      "src/generated.ts": "/* oxlint-disable -- Generated file. */\nexport const value = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/generated.ts:1: Name the rules this directive disables");
  });

  it("fails when the repository configuration cannot be read", () => {
    writeFiles({ ".oxlintrc.json": "{bad", "src/clean.ts": "export const value = 1;\n" });

    expect(() => check()).toThrow("oxlint --print-config failed");
  });

  it("reports a blanket disable, which would silence the policy rule", () => {
    writeFiles({
      "src/blanket.ts":
        "/* oxlint-disable */\n// oxlint-disable-next-line typescript/no-explicit-any -- ok\nexport const value: any = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/blanket.ts:1:");
  });

  it("reports directives that a blanket disable on the same line would silence in lint", () => {
    writeFiles({
      "src/bypass.ts":
        "/* oxlint-disable */ // oxlint-disable-line unicorn/no-abusive-eslint-disable -- Needed for this generated file.\n// oxlint-disable-next-line typescript/no-explicit-any -- ok\nexport const value: any = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/bypass.ts:1: Name the rules this directive disables");
    expect(output).toContain(
      "src/bypass.ts:1: `unicorn/no-abusive-eslint-disable` enforces the suppression policy",
    );
    expect(output).toContain(
      "src/bypass.ts:2: `typescript/no-explicit-any` must not be suppressed.",
    );
  });

  it("checks files whose names contain spaces or non-ASCII characters, whatever the diff settings", () => {
    writeFiles({
      "src/my file.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
      "src/café.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });
    git("add", "--all");
    git("config", "diff.noprefix", "true");

    const { output } = check();

    expect(output).toContain("src/my file.ts:1:");
    expect(output).toContain("src/café.ts:1:");
  });

  it("uses the pull request base from the GitHub Actions event", () => {
    const base = execFileSync("git", ["rev-parse", "base"], { cwd: repository, encoding: "utf8" });
    writeFiles({
      "event.json": JSON.stringify({ pull_request: { base: { sha: base.trim() } } }),
      "src/added.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });

    const { exitCode, output } = check({
      args: [],
      env: { GITHUB_EVENT_PATH: path.join(repository, "event.json") },
    });

    expect(exitCode).toBe(1);
    expect(output).toContain("src/added.ts:1:");
  });

  it.each([["--base=base"], ["--base", "base", "--unknown"]])(
    "accepts --base=<ref> and rejects unknown arguments: %s",
    (...args) => {
      writeFiles({ "src/clean.ts": "export const value = 1;\n" });

      expect(check({ args }).exitCode).toBe(args.includes("--unknown") ? 2 : 0);
    },
  );

  it("writes its temporary configuration outside the working tree and leaves nothing behind", () => {
    writeFiles({ "src/clean.ts": "export const value = 1;\n" });
    const written: string[] = [];
    const original = temporaryFile.withTemporaryFile;
    const spy = vi.spyOn(temporaryFile, "withTemporaryFile").mockImplementation((params) => {
      written.push(params.path);
      return original(params);
    });
    const before = readdirSync(repository).toSorted();

    try {
      expect(check().exitCode).toBe(0);
    } finally {
      spy.mockRestore();
    }

    expect(written).toHaveLength(1);
    expect(path.relative(repository, written[0]!).startsWith("..")).toBe(true);
    expect(readdirSync(repository).toSorted()).toStrictEqual(before);
    expect(existsSync(path.dirname(path.dirname(written[0]!)))).toBe(false);
  });

  it("honors .eslintignore and skips symlinks that point nowhere", () => {
    writeFiles({
      ".eslintignore": "generated/**\n",
      "generated/skipped.ts": "// oxlint-disable-next-line no-console\nconst value = ;\n",
      "src/added.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });
    symlinkSync("missing.ts", path.join(repository, "src/dangling.ts"));
    git("add", "--all");

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/added.ts:1:");
    expect(output).not.toContain("generated/skipped.ts");
  });

  it("honors the repository's ignorePatterns, which Oxlint resolves against the configuration's directory", () => {
    writeFiles({
      ".oxlintrc.json": JSON.stringify({ ignorePatterns: ["generated/**", "!generated/keep.ts"] }),
      "generated/skipped.ts": "// oxlint-disable-next-line no-console\nconst value = ;\n",
      "generated/keep.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
      "src/added.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain("src/added.ts:1:");
    expect(output).toContain("generated/keep.ts:1:");
    expect(output).not.toContain("generated/skipped.ts");
  });

  it("passes when every changed JavaScript file is ignored by the repository", () => {
    writeFiles({
      ".oxlintrc.json": JSON.stringify({ ignorePatterns: ["generated/**"] }),
      "generated/worker.js": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(0);
    expect(output).toContain("no violations");
  });

  function check(options: { args?: string[]; env?: Record<string, string> } = {}): {
    exitCode: number;
    output: string;
  } {
    let output = "";
    const { exitCode } = runCheckSuppressions({
      args: options.args ?? ["--base", "base"],
      cwd: repository,
      env: options.env ?? {},
      pluginSpecifier: PLUGIN,
      write: (text) => {
        output += text;
      },
    });
    return { exitCode, output };
  }

  function commit(message: string): void {
    git(
      "-c",
      "user.name=test",
      "-c",
      "user.email=test@example.com",
      "commit",
      "--quiet",
      "-m",
      message,
    );
  }

  function git(...args: string[]): void {
    execFileSync("git", args, { cwd: repository, stdio: "ignore" });
  }

  function writeFiles(files: Record<string, string>): void {
    for (const [file, content] of Object.entries(files)) {
      mkdirSync(path.dirname(path.join(repository, file)), { recursive: true });
      writeFileSync(path.join(repository, file), content);
    }
  }
});
