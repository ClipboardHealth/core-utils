import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { runCheckSuppressions } from "./runCheckSuppressions";

const WORKSPACE_ROOT = path.resolve(__dirname, "../../../..");
// Oxlint loads JavaScript plugins as JavaScript, so these tests use the build that `test` depends on.
const PLUGIN = path.join(WORKSPACE_ROOT, "dist/packages/oxlint-plugin/src/index.js");

describe("runCheckSuppressions", () => {
  let repository: string;

  beforeEach(() => {
    repository = mkdtempSync(path.join(tmpdir(), "check-suppressions-"));
    symlinkSync(path.join(WORKSPACE_ROOT, "node_modules"), path.join(repository, "node_modules"));
    writeFiles({
      ".gitignore": "node_modules\n",
      "package.json": '{ "private": true }\n',
      "src/existing.ts": "// oxlint-disable-next-line no-console\nconsole.log(1);\n",
    });
    git("init", "--quiet", "--initial-branch=main");
    git("add", "--all");
    git(
      "-c",
      "user.name=test",
      "-c",
      "user.email=test@example.com",
      "commit",
      "--quiet",
      "-m",
      "base",
    );
    git("branch", "base");
  });

  afterEach(() => {
    rmSync(repository, { force: true, recursive: true });
  });

  it("passes when no changed file adds a directive", () => {
    writeFiles({ "src/clean.ts": "export const value = 1;\n" });

    const { exitCode, output } = check();

    expect({ exitCode, output }).toStrictEqual({
      exitCode: 0,
      output: "cbh-check-suppressions: checked 1 changed file(s); no violations.\n",
    });
  });

  it("checks added and changed directives and leaves untouched ones alone", () => {
    writeFiles({
      "src/existing.ts":
        "// oxlint-disable-next-line no-console\nconsole.log(1);\n// oxlint-disable-next-line no-console -- ditto\nconsole.log(2);\n",
      "src/added.ts":
        "// oxlint-disable-next-line typescript/no-explicit-any -- The SDK ships no types.\nexport const value: any = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain('src/existing.ts:3: Reason "ditto" is too generic.');
    expect(output).toContain(
      "src/added.ts:1: `typescript/no-explicit-any` must not be suppressed.",
    );
    expect(output).not.toContain("src/existing.ts:1:");
  });

  it("catches a file-level disable of the policy rule, which lint cannot see", () => {
    writeFiles({
      "src/generated.ts":
        "/* oxlint-disable @clipboard-health/suppression-policy -- Generated by the schema build. */\nexport const value = 1;\n",
    });

    const { exitCode, output } = check();

    expect(exitCode).toBe(1);
    expect(output).toContain(
      "src/generated.ts:1: `@clipboard-health/suppression-policy` enforces the suppression policy",
    );
  });

  it("leaves no temporary configuration behind", () => {
    writeFiles({ "src/clean.ts": "export const value = 1;\n" });

    check();

    expect(readdirSync(repository).filter((name) => name.startsWith(".cbh-"))).toStrictEqual([]);
  });

  function check(): { exitCode: number; output: string } {
    let output = "";
    const { exitCode } = runCheckSuppressions({
      args: ["--base", "base"],
      cwd: repository,
      env: {},
      pluginSpecifier: PLUGIN,
      write: (text) => {
        output += text;
      },
    });
    return { exitCode, output };
  }

  function git(...args: string[]): void {
    execFileSync("git", args, { cwd: repository, stdio: "ignore" });
  }

  function writeFiles(files: Record<string, string>): void {
    for (const [file, content] of Object.entries(files)) {
      mkdirSync(path.dirname(path.join(repository, file)), { recursive: true });
      writeFileSync(path.join(repository, file), content);
    }
  }
});
